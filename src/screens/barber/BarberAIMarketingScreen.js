import React, { useCallback, useEffect, useState } from 'react';
import { View, Text, StyleSheet, ScrollView, Pressable, ActivityIndicator, Alert, Share } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { Ionicons } from '@expo/vector-icons';
import { colors, radius, shadow, spacing, typography } from '../../theme/colors';
import { api } from '../../api/client';

export default function BarberAIMarketingScreen({ navigation }) {
  const [templates, setTemplates] = useState([]);
  const [aiEnabled, setAiEnabled] = useState(false);
  const [posts, setPosts] = useState([]);
  const [busy, setBusy] = useState(false);
  const [busyId, setBusyId] = useState(null);

  const load = useCallback(async () => {
    try {
      const [t, p] = await Promise.all([api.aiTemplates(), api.aiPosts()]);
      // New shape: { aiEnabled, templates }. Old shape: array.
      if (Array.isArray(t)) {
        setTemplates(t);
      } else {
        setTemplates(t.templates || []);
        setAiEnabled(Boolean(t.aiEnabled));
      }
      setPosts(p);
    } catch { /* */ }
  }, []);
  useEffect(() => { load(); }, [load]);

  const generate = async (tpl) => {
    setBusy(true); setBusyId(tpl.id);
    try {
      await api.aiGenerate({ templateId: tpl.id, pct: 20, service: 'haircut' });
      load();
    } catch (e) { Alert.alert('Failed', e.message); }
    finally { setBusy(false); setBusyId(null); }
  };

  const share = (post) => Share.share({ message: post.body });

  return (
    <SafeAreaView style={styles.root} edges={['top']}>
      <View style={styles.headerRow}>
        <Pressable onPress={() => navigation.goBack()} hitSlop={10}>
          <Ionicons name="chevron-back" size={22} color={colors.text} />
        </Pressable>
        <Text style={styles.title}>AI marketing</Text>
        <View style={{ width: 22 }} />
      </View>

      <ScrollView contentContainerStyle={{ padding: spacing.lg, paddingBottom: spacing.xxl }}>
        <View style={[styles.hero, shadow.card]}>
          <Ionicons name="sparkles" size={28} color="#fff" />
          <Text style={styles.heroTitle}>Write a post in one tap</Text>
          <Text style={styles.heroSub}>Pick a template — we'll fill in your salon name, handle, and details. Share to Instagram/WhatsApp.</Text>
          <View style={styles.statusPill}>
            <Ionicons name={aiEnabled ? 'flash' : 'flash-off'} size={12} color="#fff" />
            <Text style={styles.statusText}>{aiEnabled ? 'AI live' : 'Demo (templates only)'}</Text>
          </View>
        </View>

        <Text style={styles.section}>Templates</Text>
        {templates.map((t) => (
          <View key={t.id} style={[styles.tpl, shadow.card]}>
            <View style={{ flex: 1 }}>
              <Text style={styles.tplTitle}>{t.title}</Text>
              <Text style={styles.tplKind}>{t.kind.toUpperCase()}</Text>
            </View>
            <Pressable onPress={() => generate(t)} disabled={busy} style={[styles.genBtn, busy && { opacity: 0.6 }]}>
              {busy && busyId === t.id ? (
                <ActivityIndicator color="#fff" size="small" />
              ) : (
                <Ionicons name="sparkles" size={14} color="#fff" />
              )}
              <Text style={styles.genBtnText}>Generate</Text>
            </Pressable>
          </View>
        ))}

        <Text style={styles.section}>Recently generated</Text>
        {posts.length === 0 ? (
          <Text style={{ color: colors.textMuted }}>No posts yet — generate one above.</Text>
        ) : posts.map((p) => (
          <View key={p.id} style={[styles.post, shadow.card]}>
            <Text style={styles.postTitle}>{p.title} <Text style={styles.postKind}>· {p.kind.toUpperCase()}</Text></Text>
            <Text style={styles.postBody}>{p.body}</Text>
            <Pressable onPress={() => share(p)} style={styles.shareBtn}>
              <Ionicons name="share-social" size={14} color={colors.primary} />
              <Text style={styles.shareText}>Share</Text>
            </Pressable>
          </View>
        ))}
        <Text style={styles.foot}>
          {aiEnabled
            ? 'Posts are generated by your configured LLM. Templates are still used as drafts behind the scenes so output stays on-brand.'
            : 'Currently using template fill-ins. Set ANTHROPIC_API_KEY or OPENAI_API_KEY on the backend to switch to live generation.'}
        </Text>
      </ScrollView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  root: { flex: 1, backgroundColor: colors.bg },
  headerRow: { flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between',
    paddingHorizontal: spacing.lg, paddingVertical: spacing.md },
  title: { ...typography.h1, color: colors.text },

  hero: { backgroundColor: colors.primary, borderRadius: radius.lg, padding: spacing.lg, alignItems: 'center' },
  heroTitle: { color: '#fff', ...typography.h1, marginTop: spacing.sm },
  heroSub: { color: 'rgba(255,255,255,0.9)', textAlign: 'center', marginTop: 4 },
  statusPill: {
    flexDirection: 'row', alignItems: 'center', marginTop: 10,
    backgroundColor: 'rgba(0,0,0,0.22)', paddingHorizontal: 10, paddingVertical: 4, borderRadius: 12,
  },
  statusText: { color: '#fff', fontSize: 11, fontWeight: '700', marginLeft: 4 },

  section: { ...typography.h2, color: colors.text, marginTop: spacing.lg, marginBottom: 8 },

  tpl: { flexDirection: 'row', alignItems: 'center', backgroundColor: colors.surface,
    padding: spacing.md, borderRadius: radius.md, marginBottom: 6 },
  tplTitle: { color: colors.text, fontWeight: '700' },
  tplKind: { color: colors.textMuted, fontSize: 11, marginTop: 2 },
  genBtn: { flexDirection: 'row', alignItems: 'center', backgroundColor: colors.primary,
    paddingHorizontal: 12, paddingVertical: 8, borderRadius: radius.pill },
  genBtnText: { color: '#fff', fontWeight: '800', marginLeft: 4 },

  post: { backgroundColor: colors.surface, padding: spacing.md, borderRadius: radius.md, marginBottom: 6 },
  postTitle: { color: colors.text, fontWeight: '700' },
  postKind: { color: colors.textMuted, fontWeight: '600', fontSize: 11 },
  postBody: { color: colors.text, marginTop: 8, lineHeight: 20 },
  shareBtn: { flexDirection: 'row', alignItems: 'center', alignSelf: 'flex-start', marginTop: 8 },
  shareText: { color: colors.primary, fontWeight: '700', marginLeft: 4 },

  foot: { color: colors.textMuted, fontSize: 11, marginTop: spacing.md, lineHeight: 16 },
});
